// Соответствие EVENT_TYPE ключам MISS_REASONS
export const EVENT_TO_MISS_REASON = Object.freeze({
    'weather_sunny': 'SUNNY',
    'weather_cloudy': 'CLOUDY',
    'weather_rainy': 'RAINY',
    'weather_foggy': 'FOGGY',
    'weather_stormy': 'STORMY',
});

// Получить случайную причину промаха для текущего события
export function getRandomMissReason(eventType) {
    const key = EVENT_TO_MISS_REASON[eventType] || 'UNKNOWN';
    const reasons = MISS_REASONS[key];
    return reasons[Math.floor(Math.random() * reasons.length)];
}

